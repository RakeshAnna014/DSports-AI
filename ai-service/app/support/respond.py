"""Customer-facing text and the structured `support` payload for the UI.

All text here is composed from the investigation and the decision (and, for cases, from what the backend actually returned). Nothing is
generated by a model, so nothing can be invented: every sentence is either a verified fact with its source, a labelled possibility, a
statement of what could not be verified, or the decision engine's recommendation.
"""
from __future__ import annotations

from typing import Any

from app.support.model import CASE_CATEGORY, Decision, Investigation, Outcome

MAX_FACTS = 10          # every fact the decision rests on is shown to the customer (a stalled-shipment verdict needs the "no tracking event" and "estimate passed" facts)

STATUS_MEANING = {
    "OPEN": "received, and waiting for a support executive to start on it",
    "INVESTIGATING": "being looked at",
    "WAITING_FOR_CUSTOMER": "waiting for a reply from you",
    "WAITING_FOR_EXTERNAL_PARTY": "waiting for an answer from another party (for example the courier or payment provider)",
    "RESOLVED": "resolved",
}
OUTCOME_TEXT = {
    "ANSWERED": "answered", "REFUND_PROCESSED_VIA_PAYMENT_FLOW": "a refund was processed", "RETURN_APPROVED_VIA_RETURNS_FLOW": "a return was approved",
    "REPLACEMENT_ARRANGED": "a replacement was arranged", "DELIVERY_CONFIRMED": "the delivery was confirmed", "NOT_ELIGIBLE": "not eligible",
    "NO_ACTION_NEEDED": "no action was needed", "CUSTOMER_WITHDREW": "you withdrew it", "DUPLICATE_OF_ANOTHER_CASE": "a duplicate of another case",
}


def findings_text(inv: Investigation, decision: Decision) -> str:
    """The investigation as the customer reads it: verified, possible, not verified, then what happens next."""
    lines: list[str] = []
    if inv.order:
        lines.append(f"I checked order {inv.order['order_number']}" + (f" ({inv.product['name']})" if inv.product and inv.product.get("name") else "") + ".")
    facts = [f for f in inv.facts if f.kind != "POLICY"][:MAX_FACTS]
    if facts:
        lines.append("What I verified in your DSports records:")
        lines += [f"- {f.statement}" for f in facts]
    elif not inv.unverified:
        lines.append("I did not find any matching records.")
    if inv.missing:
        lines.append("What I can't verify:")
        lines += [f"- {m.item}: {m.why}." for m in inv.missing[:4]]
    if inv.inferences:
        lines.append("Possible explanations (not confirmed):")
        lines += [f"- {i.statement}" for i in inv.inferences[:3]]
    if inv.policy:
        p = inv.policy[0]
        lines.append(f"From {p['title']}: {p['snippet'][:260].rstrip()}{'...' if len(p['snippet']) > 260 else ''}")
    lines.append(decision.recommendation)
    return "\n".join(lines)


def evidence_items(inv: Investigation) -> list[dict[str, Any]]:
    out = []
    for f in inv.facts:
        if f.kind == "POLICY":
            continue
        out.append({"kind": f.kind[:30], "ref": (f.ref or "")[:100] or None, "summary": f.statement[:400]})
    return out[:20]


def investigation_summary(inv: Investigation, decision: Decision) -> str:
    """The deterministic summary stored on the case. Built only from the investigation, and free of 'days ago' wording so that preparing
    the same proposal twice gives identical text."""
    parts = ["Verified: " + " ".join(f.statement for f in inv.facts if f.kind != "POLICY")]
    if inv.inferences:
        parts.append("Possibilities (not confirmed): " + " ".join(i.statement for i in inv.inferences))
    if inv.missing:
        parts.append("Not verified: " + "; ".join(f"{m.item} ({m.why})" for m in inv.missing))
    parts.append("Recommendation: " + decision.recommendation)
    return " ".join(parts)[:3990]


def case_arguments(inv: Investigation, decision: Decision, description: str, *, escalation_reason: str | None) -> dict[str, Any]:
    from app.support.resolve import case_subject
    args: dict[str, Any] = {
        "category": CASE_CATEGORY[inv.effective], "subject": (decision.case_subject or case_subject(inv))[:200], "description": description[:2000],
        "safety_related": inv.safety_related, "investigation_summary": investigation_summary(inv, decision), "evidence": evidence_items(inv),
        "policy_citations": [f"{p['title']} ({p['source']})"[:190] for p in inv.policy[:5]],
        "missing_information": [f"{m.item}"[:190] for m in inv.missing[:8]],
        "resolution_recommendation": decision.recommendation[:990], "escalation_reason": escalation_reason}
    if inv.order:
        args["order_id"] = inv.order["order_id"]
    if inv.product and inv.product.get("product_id"):
        args["product_id"] = inv.product["product_id"]
    return args


def escalation_sentence(esc: dict[str, Any] | None) -> str:
    state = (esc or {}).get("state", "NONE")
    if state == "REQUESTED":
        return "A person has been asked to review it, but nobody has taken the case yet."
    if state == "ACCEPTED":
        return "A support executive has taken the case."
    return ""


def case_card(case: dict[str, Any]) -> dict[str, Any]:
    return {**case, "status_meaning": STATUS_MEANING.get(case.get("status", ""), case.get("status")),
            "escalation_text": escalation_sentence(case.get("escalation"))}


def created_text(result: dict[str, Any]) -> str:
    n, st = result["case_number"], result["status"]
    outcome = result.get("outcome")
    esc = escalation_sentence(result.get("escalation"))
    if outcome == "ALREADY_OPEN":
        return (f"You already have an open case about this: {n} (status {st}: {STATUS_MEANING.get(st, st)}). I did not create a second one. "
                + (esc + " " if esc else "") + "You can add details to it or ask me for its status.")
    if outcome == "REPLAYED":
        return f"That case already exists: {n} (status {st}). Nothing new was created."
    return (f"Done. Your support case {n} has been created. Its status is {st}: {STATUS_MEANING.get(st, st)}. Priority {result.get('priority')}. "
            + (esc + " " if esc else "") + "I don't have an official response-time commitment to quote, so I won't promise one. You can ask me for its status at any time.")


def case_status_text(case: dict[str, Any]) -> str:
    n, st = case["case_number"], case["status"]
    lines = [f"Case {n}: {case.get('subject')}.", f"Status: {st} - {STATUS_MEANING.get(st, st)}. Priority: {case.get('priority')}."]
    esc = escalation_sentence(case.get("escalation"))
    if esc:
        lines.append(esc)
    if case.get("assigned_to_support_team") and st != "RESOLVED":
        lines.append("It is assigned to the support team.")
    if st == "RESOLVED":
        out = OUTCOME_TEXT.get(case.get("resolution_outcome") or "", case.get("resolution_outcome"))
        lines.append(f"Outcome: {out}." + (f" Note from support: {case['resolution_note']}" if case.get("resolution_note") else ""))
        if case.get("can_reopen"):
            lines.append("If the problem is not solved you can reopen it.")
    support_msgs = [m for m in case.get("messages", []) if m.get("from") == "SUPPORT"]
    if support_msgs:
        lines.append(f"Latest message from support: \"{support_msgs[-1]['body']}\"")
    elif st != "RESOLVED":
        lines.append("There is no message from support on this case yet.")
    return "\n".join(lines)


def cases_list_text(data: dict[str, Any], unresolved_only: bool) -> str:
    cases = data["cases"]
    if not cases:
        return "You have no open support cases." if unresolved_only else "You have no support cases."
    head = f"You have {data['count']} {'open ' if unresolved_only else ''}support case(s)" + (f" (showing {data['shown']})" if data['shown'] < data['count'] else "") + ":"
    return head + "\n" + "\n".join(f"- {c['case_number']}: {c['subject']} - {c['status']}" + (" (human review requested, not yet taken)" if c['escalation']['state'] == 'REQUESTED' else "") for c in cases)


def payload(kind: str, **parts: Any) -> dict[str, Any]:
    return {"kind": kind, **{k: v for k, v in parts.items() if v is not None}}


def investigation_payload(inv: Investigation, decision: Decision) -> dict[str, Any]:
    return payload(
        "INVESTIGATION", complaint=inv.effective.value, order=({k: inv.order[k] for k in ("order_id", "order_number", "status")} if inv.order else None),
        product=inv.product,
        evidence={"verified": [f.to_json() for f in inv.facts if f.kind != "POLICY"][:10], "inferences": [i.to_json() for i in inv.inferences[:4]],
                  "missing": [m.to_json() for m in inv.missing[:6]], "unverified_lookups": inv.unverified},
        policy=[{"title": p["title"], "source": p["source"], "snippet": p["snippet"][:240]} for p in inv.policy],
        resolution={"outcome": decision.outcome.value, "recommendation": decision.recommendation, "category": decision.category,
                    "escalation": {"recommended": decision.escalation_reason is not None, "reason": decision.escalation_reason,
                                   "state": "NOT_REQUESTED", "human_accepted": False},
                    "reasons": decision.reasons},
        safety_related=inv.safety_related)
